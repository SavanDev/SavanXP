#!/usr/bin/env python3
"""Generate a DLL's declared entry points from its declared.txt.

usage: declared.py DLL TABLE BASE_DEF OUT_C OUT_DEF

A declared entry point is exported so that a program's imports resolve, and
has no behaviour yet (dlls/common/declared.h, docs/userland/WIN32.md). Each
line of TABLE is

    Name  ARGS  RESULT

ARGS is the number of argument bytes a stdcall function pops, `cdecl` for a
function whose caller pops them (the C runtime, varargs), or `data` for a
variable: four zero bytes, exported as DATA, with no RESULT. RESULT is the
value returned in EAX, decimal or hex, possibly negative. `#` starts a
comment.

OUT_DEF is BASE_DEF with the declared names appended to its EXPORTS. A name
both in BASE_DEF and in TABLE is an error: a function is either real or
declared, never both.
"""
import re
import sys

dll, table, base_def, out_c, out_def = sys.argv[1:6]


def fail(message):
    sys.exit(f"declared.py: {message}")


def def_names(path):
    names = set()
    exports = False
    for line in open(path, encoding="utf-8"):
        line = line.split(";", 1)[0].strip()
        if not line:
            continue
        if line.upper().startswith("LIBRARY"):
            continue
        if line.upper() == "EXPORTS":
            exports = True
            continue
        if exports:
            names.add(re.split(r"[\s=@]", line, maxsplit=1)[0])
    return names


entries = []
seen = set()
for number, line in enumerate(open(table, encoding="utf-8"), 1):
    line = line.split("#", 1)[0].split()
    if not line:
        continue
    where = f"{table}:{number}"
    name = line[0]
    if name in seen:
        fail(f"{where}: {name} is declared twice")
    seen.add(name)
    if line[1:] == ["data"]:
        entries.append((name, "data", 0))
        continue
    if len(line) != 3:
        fail(f"{where}: expected Name ARGS RESULT")
    args = line[1]
    if args != "cdecl" and (not args.isdigit() or int(args) % 4 != 0 or int(args) > 256):
        fail(f"{where}: ARGS must be a multiple of 4 up to 256, or cdecl")
    try:
        result = int(line[2], 0) & 0xFFFFFFFF
    except ValueError:
        fail(f"{where}: RESULT {line[2]} is not a number")
    entries.append((name, args, result))

real = def_names(base_def)
both = sorted(real & seen)
if both:
    fail(f"{dll}: real and declared at once: {', '.join(both)}")


def symbol(name):
    """The COFF symbol of an exported name: C names take an underscore,
    C++ decorated names (starting with '?') are used as they are."""
    return f'"{name}"' if name.startswith("?") else f"_{name}"


out = [
    f"/* Generated by dlls/declared.py from {dll}'s declared.txt. Do not edit. */",
    '#include "declared.h"',
    "",
]
for index, (name, args, result) in enumerate(entries):
    if args == "data":
        out.append(f'unsigned sxw_data_{index} __asm__("{symbol(name).strip(chr(34))}") = 0;')
        continue
    stdcall = 0 if args == "cdecl" else 1
    out.append(f'sxw_declared sxw_declared_{index} = {{0, {stdcall}, "{dll}!{name}"}};')
    ret = "ret" if args == "cdecl" else f"ret ${args}"
    # A stdcall C name carries its argument bytes, as the compiler decorates
    # it (_Name@8), so that a program built against the import library links.
    sym = symbol(name)
    if stdcall and not name.startswith("?"):
        sym = f'"_{name}@{args}"'
    out.append(
        '__asm__(".text\\n.globl {sym}\\n{sym}:\\n'
        '\\tpushl $_sxw_declared_{i}\\n\\tcall _sxw_declared_hit\\n\\taddl $4, %esp\\n'
        '\\tmovl ${res}, %eax\\n\\t{ret}\\n");'.format(
            sym=sym.replace('"', '\\"'), i=index, res=hex(result), ret=ret))
with open(out_c, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")

with open(out_def, "w", encoding="utf-8") as f:
    f.write(open(base_def, encoding="utf-8").read().rstrip("\n") + "\n")
    f.write(f"    ; declared entry points (dlls/{dll.split('.')[0]}/declared.txt)\n")
    for name, args, _ in entries:
        f.write(f"    {name}{' DATA' if args == 'data' else ''}\n")
