#!/usr/bin/env python3
"""Bake fonts into C glyph tables (.inc) for SavanXP.

The OS does not parse font files at runtime: glyphs are rasterised offline here
and the generated .inc files are committed for reproducible builds.

Three modes:

  unifont  -> 1-bit fixed 8x16 console font baked from GNU UniFont's canonical
              .hex bitmaps (ASCII + Latin-1 + box drawing / block elements).
              The .hex source is used because UniFont is a bitmap font: its TTF
              is outline-only and rasterises off-grid with artefacts. Consumed
              by the kernel framebuffer console and the gfx monospace text path.

  sfd      -> proportional face baked from one hand-drawn 1-bit bitmap strike
              of a FontForge .sfd (no FreeType needed). Every coverage byte is
              0x00 or 0xff. This is how the UI body face is made, from Wine's
              MS Sans Serif 13px strike.

  noto     -> proportional face rasterised from a TTF outline by FreeType.
              Requires freetype-py. The mode name is historical: it bakes any
              proportional TTF. A pixel-font TTF comes out 1-bit only at its
              native pixel size (RetroSans: 17px); anything else is
              antialiased.

Both proportional modes cover ASCII, Latin-1 and the punctuation in NOTO_RANGES
and write the same table layout. The C prefix selects the symbols: SX_NOTO
(the historical name) for the body, SX_TITLE for window captions,
SX_PIXEL_SANS and SX_IMPACTFUL_BITS for the spare pixel faces. See
docs/desktop/UI_FONTS.md.

Regenerate (run from repo root):
  python tools/font/genfont.py unifont \
      --hex assets/desktop/fonts/unifont.hex \
      --out include/kernel/console_font_unifont.inc \
      --out system/gfx/console_font_unifont.inc
  python tools/font/genfont.py sfd \
      --sfd assets/desktop/fonts/ms_sans_serif.sfd --size 13 \
      --out system/gfx/gfx_font_noto.inc
  python tools/font/genfont.py noto \
      --ttf assets/desktop/fonts/RetroSans.ttf --size 17 \
      --prefix SX_TITLE \
      --out system/gfx/gfx_font_title.inc
  python tools/font/genfont.py noto \
      --ttf assets/desktop/fonts/PixelSans.ttf \
      --prefix SX_PIXEL_SANS \
      --out system/gfx/gfx_font_pixelsans.inc
  python tools/font/genfont.py noto \
      --ttf assets/desktop/fonts/ImpactfulBits.ttf \
      --prefix SX_IMPACTFUL_BITS \
      --out system/gfx/gfx_font_impactfulbits.inc
"""

import argparse
import os
import sys

# Cell geometry for the UniFont console glyphs.
UNI_CELL_W = 8
UNI_CELL_H = 16

# Codepoint ranges baked into the console font (inclusive). Slot 0 is reserved
# for .notdef, so real glyphs are assigned slots starting at 1.
UNI_RANGES = [
    (0x20, 0xFF),    # ASCII + Latin-1
    (0x2500, 0x257F),  # box drawing
    (0x2580, 0x259F),  # block elements
]

# Same idea for the proportional UI font. Latin-1 covers the accented letters the
# Spanish UI needs; the punctuation block is what a UI actually reaches for
# (en/em dash, curly quotes, ellipsis, bullet). Kept deliberately small: this
# table is linked into every binary.
NOTO_RANGES = [
    (0x20, 0xFF),      # ASCII + Latin-1
    (0x2010, 0x2027),  # dashes, curly quotes, bullet, ellipsis
    (0x20AC, 0x20AC),  # euro sign
]


def _parse_hex(path):
    """Parse a GNU UniFont .hex file into {codepoint: [16 row bytes]}.

    Each line is 'CCCC:hhhh...'. The bitmap is 16 rows; an 8-wide glyph encodes
    one byte per row (32 hex chars), a 16-wide glyph two bytes per row (64). We
    keep the leftmost 8 columns so every glyph lands in the fixed 8x16 cell;
    the baked ranges are all single-width, so no real data is clipped.
    """
    table = {}
    with open(path, "r", encoding="ascii") as fh:
        for line in fh:
            line = line.strip()
            if not line or ":" not in line:
                continue
            code, bits = line.split(":", 1)
            cp = int(code, 16)
            nbytes = len(bits) // 2
            stride = nbytes // UNI_CELL_H  # 1 (8-wide) or 2 (16-wide)
            if stride == 0:
                continue
            rows = []
            for r in range(UNI_CELL_H):
                base = (r * stride) * 2
                rows.append(int(bits[base:base + 2], 16))  # leftmost byte
            table[cp] = rows
    return table


def gen_unifont(hexpath, outs):
    table = _parse_hex(hexpath)
    blank = [0] * UNI_CELL_H

    glyphs = []
    # Slot 0: .notdef -> replacement char if present, else blank.
    glyphs.append(table.get(0xFFFD, blank))

    ranges = []  # (first, last, base_slot)
    for first, last in UNI_RANGES:
        base = len(glyphs)
        for cp in range(first, last + 1):
            glyphs.append(table.get(cp, blank))
        ranges.append((first, last, base))

    sb = []
    sb.append("/* Generated by tools/font/genfont.py (mode unifont) from %s." %
              os.path.basename(hexpath))
    sb.append(" * Do not edit by hand. See tools/font/genfont.py header to regenerate. */")
    sb.append("#define SX_CONSOLE_GLYPH_W %d" % UNI_CELL_W)
    sb.append("#define SX_CONSOLE_GLYPH_H %d" % UNI_CELL_H)
    sb.append("")
    sb.append("static const unsigned char kConsoleGlyphs[%d][%d] = {" %
              (len(glyphs), UNI_CELL_H))
    for slot, rows in enumerate(glyphs):
        body = ", ".join("0x%02x" % b for b in rows)
        sb.append("    {%s}, /* slot %d */" % (body, slot))
    sb.append("};")
    sb.append("")
    sb.append("struct sx_console_glyph_range { unsigned int first; unsigned int last; unsigned int base; };")
    sb.append("static const struct sx_console_glyph_range kConsoleGlyphRanges[] = {")
    for first, last, base in ranges:
        sb.append("    {0x%04x, 0x%04x, %d}," % (first, last, base))
    sb.append("};")
    sb.append("static const int kConsoleGlyphRangeCount = %d;" % len(ranges))
    sb.append("")
    sb.append("/* Look up a codepoint, falling back to slot 0 (.notdef). */")
    sb.append("static inline const unsigned char* sx_console_glyph(unsigned int cp) {")
    sb.append("    int i;")
    sb.append("    for (i = 0; i < kConsoleGlyphRangeCount; ++i) {")
    sb.append("        if (cp >= kConsoleGlyphRanges[i].first && cp <= kConsoleGlyphRanges[i].last) {")
    sb.append("            return kConsoleGlyphs[kConsoleGlyphRanges[i].base + (cp - kConsoleGlyphRanges[i].first)];")
    sb.append("        }")
    sb.append("    }")
    sb.append("    return kConsoleGlyphs[0];")
    sb.append("}")
    sb.append("")
    text = "\n".join(sb)
    for out in outs:
        _write(out, text)
        print("Wrote %d console glyphs to %s" % (len(glyphs), out))


def _noto_symbols(prefix):
    """Return C identifiers for one generated proportional face.

    Keeping the prefix in one place lets the same tool bake the normal UI
    face and separately-sized faces without making the generated tables
    collide when more than one is included in the POSIX runtime. Any SX_
    prefix works (SX_NOTO, SX_TITLE, SX_PIXEL_SANS); the part after SX_
    names the symbols. SX_NOTO and SX_NOTO_TITLE keep their historical
    names.
    """
    normalized = prefix.strip("_")
    all_parts = normalized.lower().split("_")
    if (len(all_parts) < 2 or all_parts[0] != "sx" or
            not all(part.isidentifier() for part in all_parts)):
        raise ValueError("Font symbol prefix must start with SX_ and contain C identifiers: %s" % prefix)
    parts = all_parts[1:]
    words = [part.capitalize() for part in parts]
    return {
        "macro": normalized.upper(),
        "type": "_".join(["sx"] + parts) + "_glyph",
        "range_type": "_".join(["sx"] + parts) + "_glyph_range",
        "array": "k" + "".join(words) + "Glyphs",
        "ranges": "k" + "".join(words) + "GlyphRanges",
        "coverage": "k" + "".join(words) + "Coverage",
        "range_count": "k" + "".join(words) + "GlyphRangeCount",
        "coverage_size": "k" + "".join(words) + "CoverageSize",
        "lookup": "_".join(["sx"] + parts) + "_glyph",
    }


def gen_noto(ttf, size, outs, prefix="SX_NOTO", bold=0):
    if size <= 0:
        raise ValueError("Noto font size must be positive")
    if bold < 0:
        raise ValueError("Noto faux-bold width cannot be negative")

    symbols = _noto_symbols(prefix)
    try:
        import freetype
    except ImportError:
        sys.exit("noto mode needs freetype-py: pip install freetype-py")
    face = freetype.Face(ttf)
    face.set_pixel_sizes(0, size)
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)
    line_height = face.size.height >> 6

    coverage = []
    glyphs = []  # (width, rows, left, top, advance, offset)

    def bake(cp):
        face.load_char(cp, freetype.FT_LOAD_RENDER)
        g = face.glyph
        bmp = g.bitmap
        offset = len(coverage)
        width = bmp.width
        for gy in range(bmp.rows):
            base = gy * bmp.pitch
            row = [bmp.buffer[base + gx] for gx in range(bmp.width)]
            if bold and width:
                # A small right-hand dilation is a deterministic faux bold that
                # keeps the source asset small and works at the tiny sizes used
                # by caption text. The advance stays the face's advance, just as
                # a real bold face usually keeps the text layout close.
                row = [
                    max(row[source_column]
                        for source_column in range(max(0, output_column - bold), output_column + 1)
                        if source_column < width)
                    for output_column in range(width + bold)
                ]
            coverage.extend(row)
        if bold and width:
            width += bold
        glyphs.append((width, bmp.rows, g.bitmap_left, g.bitmap_top,
                       g.advance.x >> 6, offset))

    # Slot 0 is the fallback for anything unmapped. Space, not .notdef: an
    # unknown codepoint should advance the pen, not draw a tofu box in the middle
    # of a label. This matches what the byte-indexed table did before, where an
    # out-of-range char fell back to kNotoGlyphs[0] == space.
    bake(0x20)
    slot_of = []  # (first, last, base_slot)
    for first, last in NOTO_RANGES:
        base = len(glyphs)
        for cp in range(first, last + 1):
            bake(cp)
        slot_of.append((first, last, base))

    style = " with %dpx faux-bold" % bold if bold else ""
    _emit_proportional(
        symbols,
        "mode noto) from %s @ %dpx%s" % (os.path.basename(ttf), size, style),
        ascent, descent, line_height, glyphs, coverage, slot_of, outs)


# A system bitmap font is drawn for one code page, so some of the punctuation in
# NOTO_RANGES is not in it. Where the missing character has an ASCII twin, the
# twin is drawn instead of a gap.
SFD_ALIASES = {
    0x2010: 0x2D,  # hyphen
    0x2011: 0x2D,  # non-breaking hyphen
    0x2012: 0x2D,  # figure dash
    0x2024: 0x2E,  # one dot leader
}


def _decode_sfd_base85(text):
    """Decode FontForge's bitmap encoding: Ascii85, with 'z' for four zero bytes."""
    out = bytearray()
    group = []
    for ch in text:
        if ch == "z" and not group:
            out += b"\0\0\0\0"
            continue
        group.append(ord(ch) - 33)
        if len(group) == 5:
            value = 0
            for digit in group:
                value = value * 85 + digit
            out += value.to_bytes(4, "big")
            group = []
    if group:
        kept = len(group) - 1
        group += [84] * (5 - len(group))
        value = 0
        for digit in group:
            value = value * 85 + digit
        out += value.to_bytes(4, "big")[:kept]
    return bytes(out)


def _parse_sfd_strike(path, size):
    """Read one 1-bit bitmap strike out of a FontForge .sfd.

    Returns (ascent, descent, {codepoint: glyph}) where each glyph holds the
    advance, the ink box (xmin, xmax, ymin, ymax, baseline-relative, y up) and
    the packed rows. The .sfd must use a Unicode encoding, so a BDFChar's
    encoding slot is its codepoint.
    """
    strike = None
    current = None
    glyph = None
    in_header = True
    with open(path, "r", encoding="latin-1") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if line.startswith(("BeginChars:", "StartChar:")):
                # Past this point "Encoding:" lines belong to single glyphs.
                in_header = False
            if in_header and line.startswith("Encoding:"):
                if "Unicode" not in line and "ISO10646" not in line:
                    raise ValueError("%s: bitmap glyphs must be Unicode-encoded, got %r" % (path, line))
            elif line.startswith("BitmapFont:"):
                # BitmapFont: pixelsize glyphcount ascent descent depth [foundry]
                fields = line.split()
                current = None
                if int(fields[1]) == size:
                    if int(fields[5]) != 1:
                        raise ValueError("%s: the %dpx strike is not 1-bit" % (path, size))
                    strike = {"ascent": int(fields[3]), "descent": int(fields[4]), "glyphs": {}}
                    current = strike
                glyph = None
            elif line.startswith("EndBitmapFont"):
                current = None
                glyph = None
            elif line.startswith("BDFChar:"):
                if current is None:
                    glyph = None
                    continue
                # BDFChar: orig_pos enc advance xmin xmax ymin ymax
                fields = [int(v) for v in line.split()[1:8]]
                glyph = {"advance": fields[2], "xmin": fields[3], "xmax": fields[4],
                         "ymin": fields[5], "ymax": fields[6], "data": []}
                current["glyphs"][fields[1]] = glyph
            elif glyph is not None:
                glyph["data"].append(line.strip())
    if strike is None:
        raise ValueError("%s has no %dpx bitmap strike" % (path, size))
    for glyph in strike["glyphs"].values():
        glyph["bits"] = _decode_sfd_base85("".join(glyph.pop("data")))
    return strike["ascent"], strike["descent"], strike["glyphs"]


def gen_sfd(sfd, size, outs, prefix="SX_NOTO"):
    """Bake a hand-drawn 1-bit bitmap strike into the proportional table.

    Unlike an outline rasterised at some size, a bitmap strike is the font as
    its designer drew it at exactly that pixel size: every coverage byte comes
    out 0x00 or 0xff, so the text is as crisp as a Win9x system font.
    """
    symbols = _noto_symbols(prefix)
    ascent, descent, table = _parse_sfd_strike(sfd, size)

    coverage = []
    glyphs = []
    missing = []

    def bake(cp):
        source = table.get(cp)
        if source is None and cp in SFD_ALIASES:
            source = table.get(SFD_ALIASES[cp])
        if source is None:
            # Same contract as the outline mode's slot 0: an unknown character
            # advances the pen like a space instead of drawing a box.
            space = table[0x20]
            missing.append(cp)
            glyphs.append((0, 0, 0, 0, space["advance"], len(coverage)))
            return
        width = source["xmax"] - source["xmin"] + 1
        rows = source["ymax"] - source["ymin"] + 1
        stride = (width + 7) // 8
        bits = source["bits"]
        offset = len(coverage)
        if source["xmax"] < source["xmin"] or not any(bits):
            # Blank glyph (space and friends): FontForge stores a 1x1 empty box.
            glyphs.append((0, 0, 0, 0, source["advance"], offset))
            return
        if len(bits) < rows * stride:
            raise ValueError("U+%04X: bitmap is %d bytes, needs %d" % (cp, len(bits), rows * stride))
        for row in range(rows):
            for column in range(width):
                byte = bits[row * stride + column // 8]
                coverage.append(0xFF if byte & (0x80 >> (column % 8)) else 0x00)
        # FreeType's convention, which the runtime uses: `top` is the distance
        # from the baseline up to the top edge of the first row.
        glyphs.append((width, rows, source["xmin"], source["ymax"] + 1,
                       source["advance"], offset))

    if 0x20 not in table:
        raise ValueError("%s: the %dpx strike has no space glyph" % (sfd, size))
    bake(0x20)
    del missing[:]
    slot_of = []
    for first, last in NOTO_RANGES:
        base = len(glyphs)
        for cp in range(first, last + 1):
            bake(cp)
        slot_of.append((first, last, base))

    if missing:
        print("note: %d codepoints are not in the %dpx strike and advance like a space: %s" %
              (len(missing), size, " ".join("U+%04X" % cp for cp in missing)))
    _emit_proportional(
        symbols,
        "mode sfd) from %s, %dpx bitmap strike" % (os.path.basename(sfd), size),
        ascent, descent, ascent + descent, glyphs, coverage, slot_of, outs)


def _emit_proportional(symbols, source, ascent, descent, line_height,
                       glyphs, coverage, slot_of, outs):
    """Write one proportional face as the C tables gfx_impl.inc consumes.

    Shared by the outline (noto) and hand-drawn bitmap (sfd) modes, so a face
    can move from one source to the other without the runtime noticing.
    `source` completes the "(mode ...)" sentence in the generated header.
    """
    sb = []
    sb.append("/* Generated by tools/font/genfont.py (%s." % source)
    sb.append(" * Do not edit by hand. See tools/font/genfont.py header to regenerate. */")
    sb.append("#define %s_ASCENT %d" % (symbols["macro"], ascent))
    sb.append("#define %s_DESCENT %d" % (symbols["macro"], descent))
    sb.append("#define %s_LINE_HEIGHT %d" % (symbols["macro"], line_height))
    sb.append("")
    sb.append("struct %s {" % symbols["type"])
    sb.append("    short width;")
    sb.append("    short rows;")
    sb.append("    short left;")
    sb.append("    short top;")
    sb.append("    short advance;")
    sb.append("    unsigned int offset;")
    sb.append("};")
    sb.append("")
    labels = ["fallback"]
    for first, last in NOTO_RANGES:
        labels.extend("0x%04x" % cp for cp in range(first, last + 1))
    sb.append("static const struct %s %s[%d] = {" %
              (symbols["type"], symbols["array"], len(glyphs)))
    for label, (w, r, l, t, a, o) in zip(labels, glyphs):
        sb.append("    {%d, %d, %d, %d, %d, %d}, /* %s */" % (w, r, l, t, a, o, label))
    sb.append("};")
    sb.append("")
    sb.append("struct %s { unsigned int first; unsigned int last; unsigned int base; };" %
              symbols["range_type"])
    sb.append("static const struct %s %s[] = {" %
              (symbols["range_type"], symbols["ranges"]))
    for first, last, base in slot_of:
        sb.append("    {0x%04x, 0x%04x, %d}," % (first, last, base))
    sb.append("};")
    sb.append("static const int %s = %d;" % (symbols["range_count"], len(slot_of)))
    sb.append("")
    sb.append("/* Look up a codepoint, falling back to slot 0 (space). */")
    sb.append("static inline const struct %s* %s(unsigned int cp) {" %
              (symbols["type"], symbols["lookup"]))
    sb.append("    int i;")
    sb.append("    for (i = 0; i < %s; ++i) {" % symbols["range_count"])
    sb.append("        if (cp >= %s[i].first && cp <= %s[i].last) {" %
              (symbols["ranges"], symbols["ranges"]))
    sb.append("            return &%s[%s[i].base + (cp - %s[i].first)];" %
              (symbols["array"], symbols["ranges"], symbols["ranges"]))
    sb.append("        }")
    sb.append("    }")
    sb.append("    return &%s[0];" % symbols["array"])
    sb.append("}")
    sb.append("")
    sb.append("static const unsigned char %s[] = {" % symbols["coverage"])
    line = "    "
    for i, v in enumerate(coverage):
        line += "0x%02x," % v
        if len(line) >= 96:
            sb.append(line)
            line = "    "
    if line.strip():
        sb.append(line)
    sb.append("};")
    sb.append("static const unsigned int %s = %d;" % (symbols["coverage_size"], len(coverage)))
    sb.append("")
    text = "\n".join(sb)
    for out in outs:
        _write(out, text)
        print("Wrote %d %s glyphs (%d coverage bytes) to %s" %
              (len(glyphs), symbols["macro"], len(coverage), out))


def _write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="mode", required=True)

    u = sub.add_parser("unifont", help="bake 1-bit 8x16 console font from .hex")
    u.add_argument("--hex", dest="hexpath", required=True)
    u.add_argument("--out", action="append", required=True)

    n = sub.add_parser("noto", help="bake a proportional face from a TTF outline")
    n.add_argument("--ttf", required=True)
    n.add_argument("--size", type=int, default=13)
    n.add_argument("--prefix", default="SX_NOTO",
                   help="C symbol prefix (default: SX_NOTO)")
    n.add_argument("--bold", type=int, default=0, metavar="PIXELS",
                   help="add this many pixels of faux-bold coverage")
    n.add_argument("--out", action="append", required=True)

    b = sub.add_parser("sfd", help="bake a 1-bit bitmap strike from a FontForge .sfd")
    b.add_argument("--sfd", required=True)
    b.add_argument("--size", type=int, default=13,
                   help="pixel size of the strike to bake (default: 13)")
    b.add_argument("--prefix", default="SX_NOTO",
                   help="C symbol prefix (default: SX_NOTO)")
    b.add_argument("--out", action="append", required=True)

    args = ap.parse_args()
    if args.mode == "unifont":
        gen_unifont(args.hexpath, args.out)
    elif args.mode == "noto":
        gen_noto(args.ttf, args.size, args.out, args.prefix, args.bold)
    elif args.mode == "sfd":
        gen_sfd(args.sfd, args.size, args.out, args.prefix)


if __name__ == "__main__":
    main()
