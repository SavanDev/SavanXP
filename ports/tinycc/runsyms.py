#!/usr/bin/env python3
"""Write the symbol table a static SavanXP tcc resolves `-run` programs with.

Reads the global symbols an archive defines (llvm-readelf -s), leaves out TLS,
and writes a C file with one `{name, &symbol}` entry each, named through asm
labels so no libc declaration is needed. tccrun.c's dlsym searches the table.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys

# llvm-readelf -sW: "Num: Value Size Type Bind Vis Ndx Name"
SYMBOL = re.compile(r"^\s*\d+:\s+\S+\s+\d+\s+(\S+)\s+(\S+)\s+\S+\s+(\S+)\s+(\S+)\s*$")
KEPT_TYPES = {"FUNC", "OBJECT", "NOTYPE"}
KEPT_BINDS = {"GLOBAL", "WEAK"}
C_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def symbols(readelf: str, archive: str) -> list[str]:
    output = subprocess.run([readelf, "-sW", archive], check=True, capture_output=True, text=True).stdout
    names: set[str] = set()
    for line in output.splitlines():
        match = SYMBOL.match(line)
        if not match:
            continue
        kind, bind, index, name = match.groups()
        if kind in KEPT_TYPES and bind in KEPT_BINDS and index != "UND" and C_NAME.match(name):
            names.add(name)
    return sorted(names)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--readelf", default="llvm-readelf")
    parser.add_argument("--archive", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    names = symbols(args.readelf, args.archive)
    if not names:
        print(f"runsyms: no symbols found in {args.archive}", file=sys.stderr)
        return 1
    lines = [
        "/* Generated by ports/tinycc/runsyms.py; do not edit. */",
        "struct sx_runsym { const char *name; void *address; };",
    ]
    lines += [f'extern char sx_runsym_{i} __asm__("{name}");' for i, name in enumerate(names)]
    lines.append("const struct sx_runsym sx_runsyms[] = {")
    lines += [f'    {{"{name}", &sx_runsym_{i}}},' for i, name in enumerate(names)]
    lines += ["    {0, 0},", "};", ""]
    with open(args.output, "w", encoding="ascii") as out:
        out.write("\n".join(lines))
    print(f"runsyms: {len(names)} symbols")
    return 0


if __name__ == "__main__":
    sys.exit(main())
