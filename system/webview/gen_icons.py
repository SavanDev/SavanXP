"""Draw Web Viewer's toolbar glyphs and generate icons.inc.

The art is our own and lives in this file, drawn with the house icon kit
(tools/icon_art.py, see docs/desktop/ICON_STYLE.md) so the glyphs share the
set's outline and top-left light. The toolbar's are 20x20 (SXGUI_TOOLBAR_ICON_SIZE); a
disabled toolbar button draws its glyph's silhouette embossed, so each one
must read by its shape alone. The status bar's lock is 16x16. Back and Forward are not here: Web Viewer uses
the shared ones of system/gfx/toolbar_glyphs/, as Files and Image Viewer do.

Writes icons/<name>.png (to look at) and icons.inc: one 0xAARRGGBB array per
glyph, the SX_PIXEL_FORMAT_BGRA8888 layout. Both outputs are versioned;
regenerate with:

    python system/webview/gen_icons.py

The names follow freedesktop's Icon Naming Specification.
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))

from gen_sxe_resources import read_icon_png  # noqa: E402
from icon_art import (  # noqa: E402
    BEIGE, FOLDER, GREEN, Icon, NAVY, PAPER, RED, SILVER, WHITE, WOOD, YELLOW, side_face, top_face,
)

SIZE = 20


def process_stop():
    """Stop: a red octagon with a white cross, the road sign."""
    ic = Icon(SIZE)
    ic.part(ic.poly([(6, 1), (13, 1), (18, 6), (18, 13), (13, 18), (6, 18), (1, 13), (1, 6)]), RED)
    cross = ic.line([(6, 6), (13, 13)], width=2) | ic.line([(13, 6), (6, 13)], width=2)
    ic.fill(cross, WHITE)
    return ic.image


def view_refresh():
    """Refresh: a green arrow turning round on itself."""
    ic = Icon(SIZE)
    ring = ic.disc(9.5, 10.5, 8.0) - ic.disc(9.5, 10.5, 4.0)
    ring = {(x, y) for (x, y) in ring if not (x >= 10 and y <= 9)}
    head = ic.poly([(9, 0), (16, 4), (9, 9)])
    ic.part(ring | head, GREEN)
    return ic.image


def go_home():
    """Home: a house with a red roof, a beige front and a wooden door."""
    ic = Icon(SIZE)
    ic.part(ic.rect(3, 9, 16, 19), BEIGE)
    ic.part(ic.rect(13, 1, 15, 6), side_face(RED))
    ic.part(ic.poly([(0, 10), (9, 1), (10, 1), (19, 10)]), RED)
    ic.part(ic.rect(8, 13, 11, 19), WOOD)
    return ic.image


def document_open():
    """Open: an open folder, its front flap tipped towards the viewer."""
    ic = Icon(SIZE)
    ic.part(ic.poly([(0, 3), (6, 3), (8, 5), (16, 5), (16, 18), (0, 18)]), side_face(FOLDER))
    ic.part(ic.poly([(4, 9), (19, 9), (16, 18), (0, 18)]), top_face(FOLDER))
    return ic.image


def text_html():
    """View Source: a sheet with angle brackets, markup on paper."""
    ic = Icon(SIZE)
    ic.part(ic.poly([(2, 0), (13, 0), (17, 4), (17, 19), (2, 19)]), PAPER)
    ic.part(ic.poly([(13, 0), (17, 4), (13, 4)]), SILVER)
    ink = NAVY.dark
    for (x, y) in [(7, 7), (6, 8), (5, 9), (4, 10), (5, 11), (6, 12), (7, 13)]:
        ic.put(x, y, ink)
        ic.put(x + 1, y, ink)
    for (x, y) in [(12, 7), (13, 8), (14, 9), (15, 10), (14, 11), (13, 12), (12, 13)]:
        ic.put(x - 1, y, ink)
        ic.put(x, y, ink)
    for (x, y) in [(10, 7), (10, 8), (9, 9), (9, 10), (9, 11), (8, 12), (8, 13)]:
        ic.put(x, y, ink)
    return ic.image


STATUS_SIZE = 16


def security_high():
    """The status bar's lock: a page that arrived over validated HTTPS. A
    gold padlock with a silver shackle and a dark keyhole, 16x16 for the
    status bar's pane."""
    ic = Icon(STATUS_SIZE)
    shackle = ic.disc(7.5, 6.0, 5.0) - ic.disc(7.5, 6.0, 3.0)
    shackle = {(x, y) for (x, y) in shackle if y <= 7}
    shackle |= ic.rect(3, 6, 5, 8) | ic.rect(10, 6, 12, 8)
    ic.part(shackle, SILVER)
    ic.part(ic.rect(1, 7, 14, 15), YELLOW)
    ink = YELLOW.outline
    for (x, y) in [(7, 9), (8, 9), (7, 10), (8, 10), (7, 11), (7, 12), (8, 11), (8, 12)]:
        ic.put(x, y, ink)
    return ic.image


# (name, draw, size): the toolbar's 20x20 glyphs, then the status bar's.
ICONS = [
    ("process-stop", process_stop, SIZE),
    ("view-refresh", view_refresh, SIZE),
    ("go-home", go_home, SIZE),
    ("document-open", document_open, SIZE),
    ("text-html", text_html, SIZE),
    ("security-high", security_high, STATUS_SIZE),
]


def symbol(name: str) -> str:
    return "webview_glyph_" + name.replace("-", "_")


def main() -> None:
    icon_dir = os.path.join(HERE, "icons")
    os.makedirs(icon_dir, exist_ok=True)
    lines = [
        "/* Generated by gen_icons.py. Do not edit by hand. */",
        "",
    ]
    for name, draw, size in ICONS:
        path = os.path.join(icon_dir, name + ".png")
        draw().save(path)
        _, _, pixels = read_icon_png(path)
        values = struct.unpack(f"<{size * size}I", pixels)
        lines.append(f"static const uint32_t {symbol(name)}[{size * size}] = {{")
        for row in range(size):
            chunk = values[row * size:(row + 1) * size]
            lines.append("    " + ", ".join(f"0x{value:08x}" for value in chunk) + ",")
        lines.append("};")
        lines.append("")

    out_path = os.path.join(HERE, "icons.inc")
    with open(out_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"{out_path}: {len(ICONS)} glyphs")


main()
