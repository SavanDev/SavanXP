"""Draw Savan BASIC's toolbar glyphs and program icon, and generate icons.inc.

The art is our own, drawn with the house icon kit (tools/icon_art.py) like
the shared toolbar glyphs (system/gfx/toolbar_glyphs/gen_icons.py). The
toolbar glyphs are 20x20 (SXGUI_TOOLBAR_ICON_SIZE) and embedded as
0xAARRGGBB arrays in icons.inc; the program icon is icon.png (16x16) and
icon-32.png (32x32), named by sxbide.sxres's icon_file. All outputs are
versioned; regenerate with:

    python system/sxbide/gen_icons.py

The glyph names follow freedesktop's Icon Naming Specification.
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))

from gen_sxe_resources import read_icon_png  # noqa: E402
from icon_art import (  # noqa: E402
    FOLDER, GREEN, Icon, NAVY, PAPER, RED, SILVER, TEAL, YELLOW, side_face, top_face,
)

SIZE = 20


def document_open():
    """Open Project: an open folder."""
    ic = Icon(SIZE)
    ic.part(ic.poly([(0, 4), (6, 4), (8, 6), (16, 6), (16, 17), (0, 17)]), side_face(FOLDER))
    ic.part(ic.poly([(3, 9), (19, 9), (16, 17), (0, 17)]), top_face(FOLDER))
    return ic.image


def document_save():
    """Save: a diskette, its shutter at the top and its label below."""
    ic = Icon(SIZE)
    ic.part(ic.poly([(1, 1), (16, 1), (18, 3), (18, 18), (1, 18)]), NAVY)
    ic.part(ic.rect(5, 1, 14, 7), SILVER)
    ic.fill(ic.rect(11, 2, 12, 6), NAVY.dark)
    ic.part(ic.rect(4, 11, 15, 18), PAPER, bevel=False)
    return ic.image


def media_playback_start():
    """Start: a green triangle pointing right."""
    ic = Icon(SIZE)
    ic.part(ic.poly([(4, 1), (17, 10), (4, 18)]), GREEN)
    return ic.image


def media_playback_stop():
    """End: a dark square."""
    ic = Icon(SIZE)
    ic.part(ic.rect(4, 4, 15, 15), NAVY)
    return ic.image


def window(ic, x0, y0, x1, y1, bar):
    """A window: a white client area under a navy caption `bar` pixels tall."""
    ic.part(ic.rect(x0, y0, x1, y1), PAPER)
    ic.fill(ic.rect(x0 + 1, y0 + 1, x1 - 1, y0 + bar), NAVY.base)


def application_x_executable():
    """Make SXE: a program's window with a yellow spark in its corner."""
    ic = Icon(SIZE)
    window(ic, 0, 2, 15, 16, 3)
    ic.part(ic.rect(3, 9, 10, 13), SILVER)
    ic.part(ic.poly([(15, 6), (17, 11), (19, 12), (17, 13), (15, 19), (13, 13), (11, 12), (13, 11)]), YELLOW)
    return ic.image


def program_icon(size):
    """Savan BASIC: a form being designed, a button and a text box on it."""
    ic = Icon(size)
    if size == 16:
        window(ic, 0, 1, 15, 14, 3)
        ic.part(ic.rect(2, 6, 13, 8), TEAL, bevel=False)
        ic.part(ic.rect(6, 10, 13, 12), SILVER)
    else:
        window(ic, 1, 2, 30, 28, 5)
        ic.part(ic.rect(4, 10, 27, 14), TEAL, bevel=False)
        ic.part(ic.rect(14, 18, 27, 24), SILVER)
        ic.part(ic.rect(4, 18, 10, 24), RED)
    return ic.image


GLYPHS = [
    ("document-open", document_open),
    ("document-save", document_save),
    ("media-playback-start", media_playback_start),
    ("media-playback-stop", media_playback_stop),
    ("application-x-executable", application_x_executable),
]


def symbol(name: str) -> str:
    return "ide_glyph_" + name.replace("-", "_")


def main() -> None:
    icon_dir = os.path.join(HERE, "icons")
    os.makedirs(icon_dir, exist_ok=True)
    lines = ["/* Generated by gen_icons.py. Do not edit by hand. */", ""]
    for name, draw in GLYPHS:
        path = os.path.join(icon_dir, name + ".png")
        draw().save(path)
        _, _, pixels = read_icon_png(path)
        values = struct.unpack(f"<{SIZE * SIZE}I", pixels)
        lines.append(f"static const uint32_t {symbol(name)}[{SIZE * SIZE}] = {{")
        for row in range(SIZE):
            chunk = values[row * SIZE:(row + 1) * SIZE]
            lines.append("    " + ", ".join(f"0x{value:08x}" for value in chunk) + ",")
        lines.append("};")
        lines.append("")
    program_icon(16).save(os.path.join(HERE, "icon.png"))
    program_icon(32).save(os.path.join(HERE, "icon-32.png"))

    out_path = os.path.join(HERE, "icons.inc")
    with open(out_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"{out_path}: {len(GLYPHS)} glyphs of {SIZE}x{SIZE}, and the program icon")


main()
