struct sxnw_rect {
    int x;
    int y;
    int w;
    int h;
};

struct sxnw_label {
    struct sxnw_rect rect;
    const char* text;
};

struct sxnw_button {
    struct sxnw_rect rect;
    const char* label;
    int pressed;
};

#define SXNW_FIELD_CAPACITY 64

struct sxnw_field {
    struct sxnw_rect rect;
    char text[SXNW_FIELD_CAPACITY];
    int length;
    int focused;
};

static inline int sxnw_hit(const struct sxnw_rect* rect, int x, int y) {
    return rect != 0 && x >= rect->x && y >= rect->y &&
        x < rect->x + rect->w && y < rect->y + rect->h;
}

static inline void sxnw_fill_rect(struct sxnwm_client* wm, const struct sxnw_rect* rect, uint32_t color) {
    int y = 0;
    int x = 0;
    int x0 = 0;
    int y0 = 0;
    int x1 = 0;
    int y1 = 0;

    if (wm == 0 || wm->pixels == 0 || rect == 0) {
        return;
    }
    x0 = rect->x < 0 ? 0 : rect->x;
    y0 = rect->y < 0 ? 0 : rect->y;
    x1 = rect->x + rect->w;
    y1 = rect->y + rect->h;
    if ((uint32_t)x1 > wm->width) {
        x1 = (int)wm->width;
    }
    if ((uint32_t)y1 > wm->height) {
        y1 = (int)wm->height;
    }
    for (y = y0; y < y1; y += 1) {
        for (x = x0; x < x1; x += 1) {
            wm->pixels[(uint32_t)y * wm->stride + (uint32_t)x] = color;
        }
    }
}

static inline void sxnw_draw_text(struct sxnwm_client* wm, int x, int y, const char* text, uint32_t color) {
    int row = 0;
    int col = 0;

    if (wm == 0 || wm->pixels == 0 || text == 0) {
        return;
    }
    while (*text != '\0') {
        unsigned glyph = (unsigned char)*text;
        const uint8_t* rows = kSxnwFont['?' - 32];

        if (glyph >= 32u && glyph < 127u) {
            rows = kSxnwFont[glyph - 32u];
        }
        for (row = 0; row < SXNW_FONT_HEIGHT; row += 1) {
            for (col = 0; col < SXNW_FONT_WIDTH; col += 1) {
                if ((rows[row] & (uint8_t)(0x10u >> (unsigned)col)) != 0) {
                    int px = x + col;
                    int py = y + row;

                    if (px >= 0 && py >= 0 && (uint32_t)px < wm->width && (uint32_t)py < wm->height) {
                        wm->pixels[(uint32_t)py * wm->stride + (uint32_t)px] = color;
                    }
                }
            }
        }
        x += SXNW_FONT_WIDTH + 1;
        text += 1;
    }
}

static inline void sxnw_draw_label(struct sxnwm_client* wm, const struct sxnw_label* label) {
    if (wm == 0 || label == 0) {
        return;
    }
    sxnw_draw_text(wm, label->rect.x + 2, label->rect.y + 2, label->text, SXNW_COLOR_BLACK);
}

static inline void sxnw_draw_button(struct sxnwm_client* wm, const struct sxnw_button* button) {
    struct sxnw_rect face;
    struct sxnw_rect border;

    if (wm == 0 || button == 0) {
        return;
    }
    border = button->rect;
    face = button->rect;
    face.x += 1;
    face.y += 1;
    face.w -= 2;
    face.h -= 2;
    sxnw_fill_rect(wm, &border, SXNW_COLOR_BLACK);
    sxnw_fill_rect(wm, &face, button->pressed ? SXNW_COLOR_DARK : SXNW_COLOR_FACE);
    sxnw_draw_text(wm, button->rect.x + 8, button->rect.y + 8, button->label, SXNW_COLOR_BLACK);
}

static inline void sxnw_draw_field(struct sxnwm_client* wm, const struct sxnw_field* field) {
    struct sxnw_rect inner;
    int cursor_x = 0;

    if (wm == 0 || field == 0) {
        return;
    }
    sxnw_fill_rect(wm, &field->rect, field->focused ? SXNW_COLOR_FOCUS : SXNW_COLOR_BLACK);
    inner = field->rect;
    inner.x += 1;
    inner.y += 1;
    inner.w -= 2;
    inner.h -= 2;
    sxnw_fill_rect(wm, &inner, SXNW_COLOR_WHITE);
    sxnw_draw_text(wm, field->rect.x + 4, field->rect.y + 5, field->text, SXNW_COLOR_BLACK);
    if (field->focused) {
        cursor_x = field->rect.x + 4 + field->length * (SXNW_FONT_WIDTH + 1);
        if (cursor_x + 2 < field->rect.x + field->rect.w - 2) {
            struct sxnw_rect cursor = {cursor_x, field->rect.y + 4, 2, SXNW_FONT_HEIGHT + 2};
            sxnw_fill_rect(wm, &cursor, SXNW_COLOR_BLACK);
        }
    }
}

/* Feed a printable key or backspace to a field. Returns 1 when consumed. */
static inline int sxnw_field_key(struct sxnw_field* field, int ascii) {
    if (field == 0 || !field->focused) {
        return 0;
    }
    if (ascii == 8) {
        if (field->length > 0) {
            field->length -= 1;
            field->text[field->length] = '\0';
            return 1;
        }
        return 0;
    }
    if (ascii >= 32 && ascii < 127 && field->length < SXNW_FIELD_CAPACITY - 1) {
        field->text[field->length] = (char)ascii;
        field->length += 1;
        field->text[field->length] = '\0';
        return 1;
    }
    return 0;
}
